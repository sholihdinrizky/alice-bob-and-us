INV_SBOX = [0] * 256
for i in range(256):
    INV_SBOX[SBOX[i]] = i


def xtime(a):
    # kali 2 di gf(2^8)
    a <<= 1
    if a & 0x100:
        a ^= 0x11B
    return a


def gmul(a, b):
    hasil = 0
    while b:
        if b & 1:
            hasil ^= a
        a = xtime(a)
        b >>= 1
    return hasil


def key_expansion(key):
    # hasilnya 11 round key
    w = [list(key[i:i + 4]) for i in range(0, 16, 4)]
    rcon = 1
    for i in range(4, 44):
        t = list(w[i - 1])
        if i % 4 == 0:
            t = t[1:] + t[:1]
            t = [SBOX[b] for b in t]
            t[0] ^= rcon
            rcon = xtime(rcon)
        w.append([w[i - 4][j] ^ t[j] for j in range(4)])
    return [sum(w[r * 4:r * 4 + 4], []) for r in range(11)]


def add_round_key(s, rk):
    return [a ^ b for a, b in zip(s, rk)]


def sub_bytes(s, box):
    return [box[b] for b in s]


# state urut per kolom, index = r + 4*c
def shift_rows(s):
    return [s[(r + 4 * (c + r)) % 16] for c in range(4) for r in range(4)]


def inv_shift_rows(s):
    return [s[(r + 4 * (c - r)) % 16] for c in range(4) for r in range(4)]


def mix_columns(s, inverse=False):
    m = [14, 11, 13, 9] if inverse else [2, 3, 1, 1]
    out = []
    for c in range(4):
        col = s[c * 4:c * 4 + 4]
        for r in range(4):
            v = 0
            for k in range(4):
                v ^= gmul(col[k], m[(k - r) % 4])
            out.append(v)
    return out


def encrypt_block(block, rk):
    s = add_round_key(list(block), rk[0])
    for r in range(1, 10):
        s = sub_bytes(s, SBOX)
        s = shift_rows(s)
        s = mix_columns(s)
        s = add_round_key(s, rk[r])
    s = shift_rows(sub_bytes(s, SBOX))
    return bytes(add_round_key(s, rk[10]))


def decrypt_block(block, rk):
    s = add_round_key(list(block), rk[10])
    for r in range(9, 0, -1):
        s = sub_bytes(inv_shift_rows(s), INV_SBOX)
        s = mix_columns(add_round_key(s, rk[r]), inverse=True)
    s = sub_bytes(inv_shift_rows(s), INV_SBOX)
    return bytes(add_round_key(s, rk[0]))


def cek_key(key):
    if len(key) != 16:
        raise ValueError("key harus 16 karakter")


def encrypt(key, teks):
    cek_key(key)
    rk = key_expansion(key.encode("ascii"))
    data = teks.encode("ascii")
    pad = 16 - len(data) % 16          # padding pkcs7
    data += bytes([pad]) * pad
    iv = os.urandom(16)
    prev, hasil = iv, iv
    for i in range(0, len(data), 16):
        blok = bytes(a ^ b for a, b in zip(data[i:i + 16], prev))  # xor dgn blok sebelumnya
        prev = encrypt_block(blok, rk)
        hasil += prev
    return hasil.hex()


def decrypt(key, hex_cipher):
    cek_key(key)
    rk = key_expansion(key.encode("ascii"))
    raw = bytes.fromhex(hex_cipher)
    prev, hasil = raw[:16], b""
    for i in range(16, len(raw), 16):
        blok = raw[i:i + 16]
        plain = decrypt_block(blok, rk)
        hasil += bytes(a ^ b for a, b in zip(plain, prev))
        prev = blok
    pad = hasil[-1]
    return hasil[:-pad].decode("ascii")


